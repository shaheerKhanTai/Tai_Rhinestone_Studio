"""PDF production sheet via ReportLab.

Generates a professional one- or two-section production sheet a maker can print
and work from: design name, physical dimensions, stone size/diameter, total
count, spacing, an optional colour breakdown, and a large true-aspect preview
of the design. Values shown are computed from the real design — no fabricated
material figures (coverage is labelled as an estimate).
"""
from __future__ import annotations

import io
import math
from dataclasses import dataclass, field
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.units import inch, mm
from reportlab.pdfgen import canvas as pdfcanvas
from reportlab.lib.utils import ImageReader

from app import __app_name__, __version__
from app.core.geometry import Unit, from_mm
from app.exporters.base import ExportError, atomic_write_bytes
from app.exporters.png_exporter import PngOptions, render_design_png, encode_png
from app.models.design import Design

# Brand-neutral document palette.
_INK = colors.HexColor("#1F2933")
_MUTED = colors.HexColor("#6B7684")
_RULE = colors.HexColor("#D5DBE2")
_ACCENT = colors.HexColor("#2563EB")


@dataclass(slots=True)
class ProductionSheetInfo:
    """Metadata for the production sheet header."""

    design_name: str
    unit: Unit = Unit.INCH
    stone_size_id: str = "SS10"
    stone_diameter_mm: float = 2.8
    spacing_mm: float = 0.5
    notes: str = ""
    color_counts: dict[str, int] = field(default_factory=dict)


def _fmt_dim(value_mm: float, unit: Unit) -> str:
    return f"{from_mm(value_mm, unit):.2f} {unit.symbol}"


def build_pdf_bytes(design: Design, info: ProductionSheetInfo) -> bytes:
    """Render the production sheet to PDF bytes (LETTER, portrait)."""
    if design.width_mm <= 0 or design.height_mm <= 0:
        raise ExportError("Design has invalid physical dimensions")

    buffer = io.BytesIO()
    c = pdfcanvas.Canvas(buffer, pagesize=LETTER)
    page_w, page_h = LETTER
    margin = 0.75 * inch
    x0 = margin
    y = page_h - margin

    # -- Title ------------------------------------------------------------- #
    c.setFillColor(_INK)
    c.setFont("Helvetica-Bold", 20)
    c.drawString(x0, y, "Rhinestone Production Sheet")
    y -= 0.28 * inch
    c.setFont("Helvetica", 12)
    c.setFillColor(_MUTED)
    c.drawString(x0, y, info.design_name or "Untitled")
    y -= 0.16 * inch
    c.setStrokeColor(_RULE)
    c.setLineWidth(1)
    c.line(x0, y, page_w - margin, y)
    y -= 0.3 * inch

    # -- Spec table -------------------------------------------------------- #
    rows = [
        ("Size", f"{_fmt_dim(design.width_mm, info.unit)}  ×  {_fmt_dim(design.height_mm, info.unit)}"),
        ("Total stones", f"{design.stone_count:,}"),
        ("Stone size", info.stone_size_id),
        ("Diameter", f"{info.stone_diameter_mm:.2f} mm"),
        ("Spacing (gap)", f"{info.spacing_mm:.2f} mm"),
        ("Coverage", _coverage_text(design)),
    ]
    label_x = x0
    value_x = x0 + 1.7 * inch
    for label, value in rows:
        c.setFont("Helvetica", 10.5)
        c.setFillColor(_MUTED)
        c.drawString(label_x, y, label)
        c.setFont("Helvetica-Bold", 10.5)
        c.setFillColor(_INK)
        c.drawString(value_x, y, value)
        y -= 0.24 * inch

    # -- Colour breakdown (only if multi-colour) --------------------------- #
    if len(info.color_counts) > 1:
        y -= 0.1 * inch
        c.setFont("Helvetica-Bold", 11)
        c.setFillColor(_INK)
        c.drawString(x0, y, "Colors")
        y -= 0.22 * inch
        for color, count in sorted(info.color_counts.items(), key=lambda kv: -kv[1]):
            try:
                c.setFillColor(colors.HexColor(color))
            except Exception:
                c.setFillColor(_INK)
            c.rect(x0, y - 2, 10, 10, fill=1, stroke=0)
            c.setFillColor(_INK)
            c.setFont("Helvetica", 10)
            c.drawString(x0 + 16, y, color)
            c.setFillColor(_MUTED)
            c.drawRightString(x0 + 1.7 * inch, y, f"{count:,}")
            y -= 0.2 * inch

    # -- Preview image ----------------------------------------------------- #
    preview_top = y - 0.15 * inch
    avail_w = page_w - 2 * margin
    avail_h = preview_top - margin - 0.3 * inch
    if avail_h > 0.8 * inch:
        _draw_preview(c, design, x0, margin + 0.3 * inch, avail_w, avail_h)

    # -- Footer ------------------------------------------------------------ #
    c.setFont("Helvetica", 8)
    c.setFillColor(_MUTED)
    c.drawString(x0, margin - 0.1 * inch,
                 f"Generated by {__app_name__} {__version__}")
    c.drawRightString(page_w - margin, margin - 0.1 * inch,
                      "Preview is illustrative; use the SVG/DXF for production.")

    c.showPage()
    c.save()
    return buffer.getvalue()


def _coverage_text(design: Design) -> str:
    if design.stone_count == 0:
        return "—"
    return f"~{_coverage_pct(design):.0f}% of area (est.)"


def _coverage_pct(design: Design) -> float:
    area = design.width_mm * design.height_mm
    if area <= 0:
        return 0.0
    stone_area = sum(math.pi * (s.diameter / 2.0) ** 2 for s in design.stones)
    return 100.0 * stone_area / area


def _draw_preview(c, design: Design, x: float, y_bottom: float, box_w: float, box_h: float) -> None:
    """Render the design to a PNG and place it centred inside the box."""
    # Choose a raster width proportional to the box, capped for size.
    px_w = int(min(2400, max(800, box_w / inch * 200)))
    rgba = render_design_png(design, PngOptions(width_px=px_w))
    img = ImageReader(io.BytesIO(encode_png(rgba)))
    iw, ih = rgba.shape[1], rgba.shape[0]
    aspect = ih / iw
    draw_w = box_w
    draw_h = draw_w * aspect
    if draw_h > box_h:
        draw_h = box_h
        draw_w = draw_h / aspect
    draw_x = x + (box_w - draw_w) / 2.0
    draw_y = y_bottom + (box_h - draw_h) / 2.0
    # Frame.
    c.setStrokeColor(_RULE)
    c.setLineWidth(1)
    c.rect(draw_x, draw_y, draw_w, draw_h, fill=0, stroke=1)
    c.drawImage(img, draw_x, draw_y, width=draw_w, height=draw_h, mask="auto")


def export_pdf(design: Design, path: str | Path, info: ProductionSheetInfo) -> Path:
    """Write the production sheet PDF to ``path`` atomically."""
    data = build_pdf_bytes(design, info)
    return atomic_write_bytes(path, data)
