"""SVG export: real vector circles at true physical dimensions.

The output is a proper SVG document whose ``width``/``height`` carry physical
units and whose ``viewBox`` establishes ``1 user unit == 1 document unit``, so
the file opens at the correct real-world size in Illustrator, Inkscape, laser
software and Cricut Design Space. Every stone is a ``<circle>`` — this is a
vector design, not a rasterised screenshot.

Two entry points:

* :func:`export_svg` — a general-purpose SVG in millimetres. Stones are grouped
  by colour (each colour is a ``<g>`` with a shared ``fill``), which keeps files
  compact today and extends cleanly to multi-colour designs.
* :func:`export_cricut_svg` — a Cricut-oriented SVG in **inches** (Cricut's
  native unit), flattened to a single cut layer, with an optional **hole
  allowance** added to each circle so a cut template stencil lets stones drop
  in. All Cricut-specific rules live here, isolated from the generic path.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from app import __app_name__, __version__
from app.core.geometry import Unit
from app.exporters.base import ExportError, atomic_write_text
from app.models.design import Design

_SVG_NS = "http://www.w3.org/2000/svg"


@dataclass(slots=True)
class SvgOptions:
    """Parameters controlling SVG generation."""

    doc_unit: Unit = Unit.MM
    #: Added to every stone *radius* before scaling (Cricut uses this for the
    #: template hole allowance). In millimetres.
    radius_delta_mm: float = 0.0
    #: When true, each stone uses its own colour; otherwise ``single_fill`` is
    #: applied to the whole design as one layer.
    per_stone_color: bool = True
    single_fill: str = "#1F2933"
    stroke: str | None = None
    stroke_width_mm: float = 0.0
    include_boundary: bool = False
    boundary_stroke: str = "#FF0000"
    precision: int = 4
    group_id: str = "rhinestones"


def _fmt(value: float, precision: int) -> str:
    """Compact fixed-point formatting with trailing zeros trimmed."""
    s = f"{value:.{precision}f}"
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return s or "0"


def _xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def render_svg(design: Design, options: SvgOptions) -> str:
    """Render ``design`` to an SVG document string."""
    unit = options.doc_unit
    f = 1.0 / unit.mm_per_unit  # millimetres -> document units
    p = options.precision

    w_doc = design.width_mm * f
    h_doc = design.height_mm * f

    stroke_doc = options.stroke_width_mm * f

    lines: list[str] = []
    lines.append('<?xml version="1.0" encoding="UTF-8" standalone="no"?>')
    lines.append(
        f'<svg xmlns="{_SVG_NS}" version="1.1" '
        f'width="{_fmt(w_doc, p)}{unit.symbol}" height="{_fmt(h_doc, p)}{unit.symbol}" '
        f'viewBox="0 0 {_fmt(w_doc, p)} {_fmt(h_doc, p)}">'
    )
    lines.append(
        f"  <title>{_xml_escape(__app_name__)} design</title>"
    )
    lines.append(
        f"  <desc>{design.stone_count} stones; "
        f"{_fmt(design.width_mm, 2)}mm x {_fmt(design.height_mm, 2)}mm; "
        f"generated by {_xml_escape(__app_name__)} {__version__}</desc>"
    )

    if options.include_boundary:
        lines.append(
            f'  <rect x="0" y="0" width="{_fmt(w_doc, p)}" height="{_fmt(h_doc, p)}" '
            f'fill="none" stroke="{options.boundary_stroke}" '
            f'stroke-width="{_fmt(max(stroke_doc, 0.2 * f), p)}" id="boundary"/>'
        )

    def circle(cx: float, cy: float, r: float) -> str:
        return f'<circle cx="{_fmt(cx, p)}" cy="{_fmt(cy, p)}" r="{_fmt(r, p)}"/>'

    stroke_attr = ""
    if options.stroke:
        stroke_attr = f' stroke="{options.stroke}" stroke-width="{_fmt(stroke_doc, p)}"'

    if options.per_stone_color:
        # One <g> per distinct colour; circles inherit the group fill.
        by_color: dict[str, list[str]] = {}
        for s in design.stones:
            cx, cy = s.x * f, s.y * f
            r = (s.radius + options.radius_delta_mm) * f
            by_color.setdefault(s.color, []).append(circle(cx, cy, r))
        lines.append(f'  <g id="{_xml_escape(options.group_id)}">')
        for idx, (color, circles) in enumerate(by_color.items()):
            lines.append(f'    <g fill="{color}"{stroke_attr} id="color-{idx}">')
            lines.extend(f"      {c}" for c in circles)
            lines.append("    </g>")
        lines.append("  </g>")
    else:
        # Single flattened cut layer (Cricut).
        lines.append(
            f'  <g id="{_xml_escape(options.group_id)}" '
            f'fill="{options.single_fill}"{stroke_attr}>'
        )
        for s in design.stones:
            cx, cy = s.x * f, s.y * f
            r = (s.radius + options.radius_delta_mm) * f
            lines.append(f"    {circle(cx, cy, r)}")
        lines.append("  </g>")

    lines.append("</svg>")
    lines.append("")
    return "\n".join(lines)


def export_svg(design: Design, path: str | Path, options: SvgOptions | None = None) -> Path:
    """Write a general-purpose SVG (millimetres) for ``design``."""
    options = options or SvgOptions()
    if design.width_mm <= 0 or design.height_mm <= 0:
        raise ExportError("Design has invalid physical dimensions")
    svg = render_svg(design, options)
    return atomic_write_text(path, svg)


def export_cricut_svg(
    design: Design,
    path: str | Path,
    *,
    hole_allowance_mm: float = 0.8,
    fill: str = "#000000",
    precision: int = 5,
) -> Path:
    """Write a Cricut-oriented SVG in inches with a single cut layer.

    ``hole_allowance_mm`` is added to each stone's *diameter* so a cut template
    stencil has holes slightly larger than the stones (default 0.8 mm). All
    Cricut-specific conventions are contained here.
    """
    if design.width_mm <= 0 or design.height_mm <= 0:
        raise ExportError("Design has invalid physical dimensions")
    if hole_allowance_mm < 0:
        raise ExportError("Hole allowance must not be negative")
    options = SvgOptions(
        doc_unit=Unit.INCH,
        radius_delta_mm=hole_allowance_mm / 2.0,
        per_stone_color=False,
        single_fill=fill,
        precision=precision,
        group_id="cricut-cut",
    )
    svg = render_svg(design, options)
    return atomic_write_text(path, svg)
